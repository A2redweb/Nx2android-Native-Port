#!/usr/bin/env python3
"""Makes upstream's host game-independent: one prebuilt libdmhost that holds every game's profile and picks one at start.

Usage: gen_universal_host.py <upstream checkout> <work dir> <out include dir>
  1. copies upstream's nxnative/dm into <work dir> (a copy; upstream's checkout is not changed),
  2. writes game_profile.h / android_profile.h / universal_profile.c into <out include dir>: every DM_GAME_* macro becomes a field of the selected profile
     (g_dm_prof->field), the gamepad layouts become one table indexed by the selected game,
  3. patches the few C sites that need a compile-time value (the arrays and the two #ifdef) with exact string replacements; a replacement that no longer matches
     stops the build, so a change in upstream shows up in CI instead of as a wrong host.
The game is chosen at start by the environment variable DM_GAME (the game ID, i.e. the title ID folder name).
"""
import re, shutil, sys
from pathlib import Path

up, work, inc = (Path(a).resolve() for a in sys.argv[1:4])
dm = work / 'dm'
if dm.exists(): shutil.rmtree(dm)
shutil.copytree(up / 'nxnative' / 'dm', dm, symlinks=True)
sys.path.insert(0, str(dm / 'games')); sys.path.insert(0, str(dm / 'android' / 'tools'))
import game, android_profile   # noqa: E402

games = sorted(game.all_games(), key=lambda g: g.id)
DEF = re.compile(r'#define (DM_GAME_[A-Z_0-9]+) (.*)')
per = []   # [{macro: value}] per game, in the order of games
for g in games:
    d = {}
    for line in game.header(g).splitlines():
        m = DEF.fullmatch(line)
        if m: d[m.group(1)] = m.group(2)
    per.append(d)

ARRAYS = {'DM_GAME_MODULES', 'DM_GAME_NMOD', 'DM_GAME_DISPLAY_VERSIONS'}
OPTIONAL = {'DM_GAME_SHARED_FONT_TTF': '-1', 'DM_GAME_NVN_API_MAJOR': '-1', 'DM_GAME_NVN_API_MINOR': '-1'}   # absent = decided by the SDK version
names = sorted(({k for d in per for k in d} | set(OPTIONAL)) - ARRAYS)
def ctype(name):
    vals = [d[name] for d in per if name in d]
    if not vals: return 'int'   # a field no profile sets (an optional one)
    if all(v.startswith('"') for v in vals): return 'const char *'
    if any(v.endswith('ull') for v in vals): return 'unsigned long long'
    return 'int'
types = {n: ctype(n) for n in names}
field = lambda n: n[len('DM_GAME_'):].lower()

modmax = max(len(d['DM_GAME_MODULES'].strip('{}').split(',')) for d in per)
vermax = max((d['DM_GAME_DISPLAY_VERSIONS'].count('{') for d in per), default=0) or 1

H = ['// Generated by tools/gen_universal_host.py; do not edit', '#pragma once',
     'struct dm_prof {']
H += [f'    {types[n]}{"" if types[n].endswith("*") else " "}{field(n)};' for n in names]
H += [f'    int nmod; const char *modules[{modmax}];', f'    int nver; struct {{ const char *build, *ver; }} versions[{vermax}];', '};',
      'extern const struct dm_prof *g_dm_prof; extern int g_dm_prof_index; extern const struct dm_prof g_dm_profiles[]; extern const int g_dm_nprofiles;']
H += [f'#define {n} (g_dm_prof->{field(n)})' for n in names]
H += ['#define DM_GAME_NMOD (g_dm_prof->nmod)', '#define DM_GAME_MODULES (g_dm_prof->modules)', '#define DM_GAME_NVERSIONS (g_dm_prof->nver)', '#define DM_GAME_DISPLAY_VERSIONS (g_dm_prof->versions)', '']
(inc).mkdir(parents=True, exist_ok=True)
(inc / 'game_profile.h').write_text('\n'.join(H))

def lit(s): return s
C = ['// Generated by tools/gen_universal_host.py; do not edit', '#include <stdlib.h>', '#include <string.h>', '#include <stdio.h>', '#include "game_profile.h"',
     'const struct dm_prof g_dm_profiles[] = {']
for g, d in zip(games, per):
    row = []
    for n in names:
        v = d.get(n, OPTIONAL.get(n))
        if v is None: v = '""' if types[n].endswith('*') else '0'
        row.append(v)
    mods = d['DM_GAME_MODULES'].strip('{}').strip()
    mods = [m.strip() for m in re.findall(r'"(?:[^"\\]|\\.)*"', mods)]
    vers = re.findall(r'\{("(?:[^"\\]|\\.)*"), ("(?:[^"\\]|\\.)*")\}', d['DM_GAME_DISPLAY_VERSIONS'])
    row.append(f'{len(mods)}, {{{", ".join(mods)}}}')
    row.append(f'{len(vers)}, {{{", ".join("{" + b + ", " + v + "}" for b, v in vers)}}}')
    C.append('    {' + ', '.join(row) + '},')
C += ['};', f'const int g_dm_nprofiles = {len(games)};',
      'const struct dm_prof *g_dm_prof = &g_dm_profiles[0]; int g_dm_prof_index;',
      '// DM_GAME (the game ID) picks the profile before main runs; an unknown ID stops the host, a missing one takes the first profile',
      '__attribute__((constructor(101))) static void dm_prof_select(void) {',
      '    const char *e = getenv("DM_GAME"); if (!e || !*e) return;',
      '    for (int i = 0; i < g_dm_nprofiles; i++) if (!strcmp(g_dm_profiles[i].id, e)) { g_dm_prof = &g_dm_profiles[i]; g_dm_prof_index = i; return; }',
      '    fprintf(stderr, "[RED] DM_GAME=%s: no such game profile\\n", e); exit(2);', '}', '']
(dm / 'host' / 'universal_profile.c').write_text('\n'.join(C))   # built with the other host sources

# the gamepad layouts: every game's, one table
aov = []
for g in games:
    p = android_profile.AndroidProfile(g) if (g.dir / 'android.tsv').is_file() else None
    h = android_profile.header(p)
    n = int(re.search(r'#define DM_AOV_N (\d+)', h).group(1))
    t = re.search(r'#define DM_AOV_TABLET \\\n(.*?)\n#define DM_AOV_PHONE \\\n(.*)', h, re.S)
    aov.append((n, t.group(1).replace(' \\\n', '\n'), t.group(2).replace(' \\\n', '\n').strip()))
if len({a[0] for a in aov}) != 1: sys.exit('the games have different numbers of gamepad controls: the table needs one size')
body = ',\n'.join('{{' + a[1].strip() + '},\n{' + a[2] + '}}' for a in aov)
(inc / 'android_profile.h').write_text('// Generated by tools/gen_universal_host.py; do not edit\n#pragma once\n#define DM_ANDROID_STATUS "universal"\n'
    f'#define DM_AOV_N {aov[0][0]}\n#define DM_NGAMES {len(games)}\n#define DM_AOV_ALL ' + body.replace('\n', ' \\\n') + '\n')

# patches: (file, old, new); each must match exactly once
def patch(rel, old, new):
    f = dm / rel; s = f.read_text(encoding='utf-8')
    if s.count(old) != 1: sys.exit(f'[RED] {rel}: upstream changed, the patch no longer matches:\n{old}')
    f.write_text(s.replace(old, new), encoding='utf-8')
